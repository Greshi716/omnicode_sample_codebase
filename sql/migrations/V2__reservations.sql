CREATE TABLE IF NOT EXISTS LIB_RESERVATIONS (
    reservation_id VARCHAR(64) PRIMARY KEY,
    book_id VARCHAR(64) NOT NULL REFERENCES LIB_BOOKS(book_id) ON DELETE CASCADE,
    member_id VARCHAR(64) NOT NULL REFERENCES LIB_MEMBERS(member_id) ON DELETE CASCADE,
    reservation_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    fulfilled BOOLEAN DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS idx_lib_res_book ON LIB_RESERVATIONS(book_id);
CREATE INDEX IF NOT EXISTS idx_lib_res_member ON LIB_RESERVATIONS(member_id);
